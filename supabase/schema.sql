-- Macadamia Outbound Engine — Supabase schema (Postgres)
-- Run in Supabase SQL editor after project creation.

create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  company text unique not null,
  hq_country text,
  tier text,
  sector text,
  source text,
  notes text,
  icp_fit_score numeric default 0,
  icp_fit_reasons jsonb default '[]',
  status text default 'watching',
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.signals (
  id bigint generated by default as identity primary key,
  account_id bigint references public.accounts(id) on delete cascade,
  type text, -- project_win | qa_hiring | news_hit | other
  description text,
  url text,
  signal_date date,
  strength int default 1,
  source text default 'engine',
  discovered_at timestamptz default now(),
  unique(account_id, type, url)
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  account_id bigint references public.accounts(id) on delete cascade,
  name text, title text, linkedin_url text, email text,
  email_confidence text, role_type text default 'quality_lead',
  unique(account_id, linkedin_url)
);

create table if not exists public.drafts (
  id bigint generated by default as identity primary key,
  account_id bigint references public.accounts(id) on delete cascade,
  contact_id bigint references public.contacts(id),
  stage text default 'E1',
  subject text, body text,
  grounding_json jsonb,
  status text default 'DRAFT', -- DRAFT|APPROVED|QUEUED|SENT|REPLIED|MEETING|KILLED
  reviewed_by text, sent_at timestamptz, reply_notes text,
  created_at timestamptz default now()
);

create table if not exists public.discovery_queue (
  id bigint generated by default as identity primary key,
  title text, url text unique, pub text, source_name text,
  icp_density int, icp_hits jsonb, status text default 'new',
  created_at timestamptz default now()
);

create table if not exists public.runs (
  id bigint generated by default as identity primary key,
  scanner text, started_at timestamptz default now(), finished_at timestamptz,
  new_accounts int, new_signals int, notes text
);

-- demo is read-only public: the demo link shows everything, edits stay local
alter table public.accounts enable row level security;
alter table public.signals enable row level security;
alter table public.contacts enable row level security;
alter table public.drafts enable row level security;
alter table public.discovery_queue enable row level security;
alter table public.runs enable row level security;

create policy "public read accounts" on public.accounts for select using (true);
create policy "public read signals" on public.signals for select using (true);
create policy "public read contacts" on public.contacts for select using (true);
create policy "public read drafts" on public.drafts for select using (true);
create policy "public read discovery" on public.discovery_queue for select using (true);
create policy "public read runs" on public.runs for select using (true);
